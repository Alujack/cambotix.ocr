// Copies the Python engine's layout templates into src/documents/templates.ts,
// so both engines read the same regions. `npm test` fails when they drift.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const source = new URL("../../core-python/src/khmerocr/documents/templates/", import.meta.url);
const target = new URL("../src/documents/templates.ts", import.meta.url);

export function renderTemplates() {
  const templates = readdirSync(source).filter((name) => name.endsWith(".json")).sort()
    .map((name) => JSON.parse(readFileSync(new URL(name, source), "utf8")));
  return "// Generated by scripts/sync-templates.mjs from packages/core-python/src/khmerocr/\n"
    + "// documents/templates/*.json. Do not edit; run `node scripts/sync-templates.mjs`.\n"
    + 'import type { TemplateData } from "./layout.js";\n\n'
    + "export const BUILTIN_TEMPLATES: Readonly<Record<string, TemplateData>> = "
    + JSON.stringify(Object.fromEntries(templates.map((t) => [t.template_id, t])), null, 2) + ";\n";
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split("/").pop())) {
  writeFileSync(target, renderTemplates());
}
